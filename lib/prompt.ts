export function buildUserPrompt(
  text: string,
  mode: ZhouliMode,
  level: ZhouliLevel,
) {
  const levelDesc = levelInstructions[level];
  const modeDesc = modeInstructions[mode];

  return `${modeDesc}
${levelDesc}

硬性要求：
- 使用虚构地名（洛圣都、夜之城、哥谭市等），禁止用真实国家名
- 核心要写离谱的"行动"，不是"写了什么文件"——发直升机、出动12人、全市停电，不是写17页报告
- 只用一个数字，不要每次都写17
- 只写一个国家，不要美日德串讲
- 先讲故事，再升华，不要先解释再讽刺
- 对比必须狠：外国越离谱国内越草台
- 结尾用"不是××，不是××，只是××"升华句式
- 现代白话，禁止文言文

${JSON.stringify(text)}`;
}
